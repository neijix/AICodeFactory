#!/usr/bin/env python3
"""Generate docs/reference/cli.md from `bin/aicf --help` and each command's `--help`.

    python3 tests/gen-cli-reference.py           # (re)write docs/reference/cli.md
    python3 tests/gen-cli-reference.py --check   # exit 1 when the file is stale

The help text is the source of truth: never edit cli.md by hand. Output is deterministic: the
commands run with a throw-away HOME and no overlay, and the checkout path and $HOME are
replaced by placeholders. Stdlib only.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference" / "cli.md"
AICF = ROOT / "bin" / "aicf"
COMMANDS = ["init", "sync", "update", "doctor", "setup", "uninstall", "projects"]

# Help text that names something only the maintainer has. The public page must not carry it;
# fix the script's help instead, after which this entry matches nothing and can go.
# (pattern, replacement) regular expressions.
REDACT = [
    (r"; [A-Z0-9]+'s Sync all\)", ")"),
]


def run_help(args: list[str], home: str) -> tuple[int, str]:
    env = {
        "PATH": os.environ.get("PATH", "/usr/bin:/bin"),
        "HOME": home,
        "LANG": "C.UTF-8",
        "LC_ALL": "C.UTF-8",
        "AI_TEMPLATE_OVERLAY_DIR": "none",
        "AI_WORK_ROOTS": "none",
        "AI_PRIVATE_TERMS_FILE": "none",
        "AI_CONTEXT_REMOTE": "none",
        "GIT_CONFIG_NOSYSTEM": "1",
    }
    proc = subprocess.run(
        ["sh", str(AICF), *args],
        cwd=home,
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        timeout=60,
    )
    return proc.returncode, proc.stdout.decode("utf-8", "replace")


def clean(text: str, home: str) -> str:
    text = text.replace(str(ROOT), "<factory>").replace(home, "~")
    real_home = os.path.expanduser("~")
    if real_home and real_home != "/":
        text = text.replace(real_home, "~")
    for old, new in REDACT:
        text = re.sub(old, new, text)
    lines = [line.rstrip() for line in text.replace("\r\n", "\n").split("\n")]
    while lines and not lines[-1]:
        lines.pop()
    return "\n".join(lines)


def render() -> tuple[str, list[str]]:
    notes: list[str] = []
    with tempfile.TemporaryDirectory(prefix="aicf-cli-ref-") as tmp:
        home = os.path.realpath(tmp)
        parts = [
            "# CLI reference",
            "",
            "<!-- GENERATED by tests/gen-cli-reference.py from the commands' --help. Do not edit:",
            "     run `python3 tests/gen-cli-reference.py` after changing a help text. -->",
            "",
            "`aicf` is the single entry point (`bin/aicf`; on Windows `bin\\aicf.ps1`, PowerShell 7).",
            "Every argument after the command is passed to the script behind it unchanged.",
            "This page is the verbatim `--help` of each command; `<factory>` stands for the",
            "folder you cloned AICodeFactory into.",
            "",
            "On Windows, PowerShell binds a single-word switch such as `--yes` to `-Yes`, but not a",
            "multi-word one: write `-DryRun`, not `--dry-run` (see",
            "[Windows specifics](../how-to/windows.md)).",
            "",
            "Commands: " + ", ".join(f"[`{c}`](#aicf-{c})" for c in COMMANDS) + ".",
            "",
            "## `aicf`",
            "",
        ]
        rc, out = run_help(["--help"], home)
        parts += ["```text", clean(out, home), "```", ""]
        for cmd in COMMANDS:
            rc, out = run_help([cmd, "--help"], home)
            parts += [f"## `aicf {cmd}`", ""]
            if rc != 0 and "unknown command" in out:
                notes.append(f"`aicf {cmd}` does not exist in this checkout yet")
                parts += [f"`aicf {cmd}` is not available in this version.", ""]
                continue
            if rc != 0:
                notes.append(f"`aicf {cmd} --help` exited {rc}")
            parts += ["```text", clean(out, home), "```", ""]
    return "\n".join(parts).rstrip("\n") + "\n", notes


def main(argv: list[str]) -> int:
    check = "--check" in argv
    text, notes = render()
    for note in notes:
        print(f"gen-cli-reference: note: {note}", file=sys.stderr)
    if check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(
                "docs/reference/cli.md is stale — run: python3 tests/gen-cli-reference.py",
                file=sys.stderr,
            )
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
